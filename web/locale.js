export function setLanguage(value){language=value==='hu'?'hu':'en';}
export function tr(value){
  if(language!=='hu'||typeof value!=='string')return value;
  if(Object.prototype.hasOwnProperty.call(hu,value))return hu[value];
  return value;
}
export function reasonText(text){
  if(language!=='hu')return text;
  return text.split('\n').map(line=>line.split(' · ').map(part=>{
    const mode=/^mode (.+) is unverified$/.exec(part);
    if(mode)return 'nem igazolt mód: '+mode[1];
    if(part.endsWith('; no verified eligible installation'))return tr(part.split(';')[0])+' – nincs ellenőrzött, használható telepítés';
    const verified=/^verified (.+) skill$/.exec(part);
    return verified?'ellenőrzött skill ('+tr(verified[1])+')':tr(part);
  }).join(' · ')).join('\n');
}

